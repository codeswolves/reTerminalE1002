# 为什么临时任务单独一套枚举、而不复用 QUADRANT:
# 四象限回答的是"这件事该不该做"(价值 × 紧迫性), 而机动消耗要回答的是
# **"什么吃掉了我的时间"**。两者维度不同 —— 突发绝大多数本来就是 C/D 类,
# 硬套象限只会得出"D 类很多"这种没有信息量的结论。
#
# 为什么必须归类而非自由文本: 自由文本统计不出"最常被什么打断",
# 也就无法反哺"机动额度该不该调"。与 BLOCKER_ORDER 是同一条理由(§2.9.4)。
